def seed_database(db):
    # Check if first fish is already Red Dragon Betta in USD (price ~38.99)
    first_fish = db.query(Fish).first()
    if first_fish and first_fish.name == "Red Dragon Betta" and first_fish.price < 100:
        return

    # Clear old records to guarantee clean English USD catalog
    db.query(OrderItem).delete()
    db.query(Order).delete()
    db.query(Review).delete()
    db.query(Fish).delete()
    db.commit()

    for item in SAMPLE_FISHES:
        reviews_data = item.pop("reviews", [])
        fish = Fish(**item)
        db.add(fish)
        db.flush()

        for rev in reviews_data:
            review = Review(
                fish_id=fish.id,
                author_name=rev["author_name"],
                rating=rev["rating"],
                comment=rev["comment"]
            )
            db.add(review)

    db.commit()
